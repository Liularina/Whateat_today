/**
 * nutrition_facts 内置基础数据（Phase 5）
 *
 * ⚠️ 数值口径说明（务必阅读）
 *
 * 1. 这些是**参考值**，量级取自公开食物成分表的常见条目并做了取整，
 *    用于第一阶段 MVP 的「估算」展示，不是实验室实测值。
 *    上线前请用权威数据替换本文件，或直接把数据写进云数据库后停用本表。
 * 2. 单位口径：
 *    - per100g.*       每 100 克**可食部**的营养值
 *    - edibleRate      **可食部比例**（0~1），带皮 / 带壳 / 带骨的食材小于 1
 *    - averageWeight   单个 / 每袋 / 每盒的**毛重**（克）；未知为 null
 * 3. 换算口径（与规范第 5 章公式一致）：
 *    可食克数 = 数量 × 单位克数 × edibleRate
 *    某项营养 = 可食克数 ÷ 100 × per100g.该项
 *    因此 g / kg 输入也一律乘 edibleRate；对于本来就按可食部称重的食材
 *    （绝大多数米面肉蛋），edibleRate 就是 1，不受影响。
 * 4. 拿不准的食材**不要往这里加**，宁可让它走 nutritionStatus = partial，
 *    也不要编造数值 —— 规范明确要求「不要让 AI 猜」。
 *
 * standardName 必须与 ingredient 云函数别名表归一后的标准名一致，
 * 否则食材库存里的名称查不到营养数据。
 */

/** nutrition_facts 集合文档（不含 _id，由数据库生成） */
function fact(standardName, calories, protein, fat, carbohydrate, averageWeight, edibleRate) {
  return {
    standardName: standardName,
    per100g: {
      calories: calories,
      protein: protein,
      fat: fat,
      carbohydrate: carbohydrate,
    },
    edibleRate: edibleRate === undefined ? 1 : edibleRate,
    averageWeight: averageWeight === undefined ? null : averageWeight,
    source: 'internal',
  };
}

